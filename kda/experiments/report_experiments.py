"""Capacity, overwrite/recency, and edit-locality experiments (issue #34).

This module is the quantitative backbone of the Phase 4 results report
(``docs/PHASE4_RESULTS.md``, generated by ``examples/phase4_results_report.py``).
It reuses the #35 task generators, the #26 variant registry, the #27 state
replay, and the #28 cluster-bootstrap machinery, and it follows the same
pre-registration discipline as #28/#38: every choice lives in the frozen
configs below, which are embedded verbatim in the experiment reports *before*
any results are collected.

Three experiment families:

- **Capacity / interference** (:class:`CapacityConfig`). On the #35
  key-collision task, recall accuracy (fraction of queries whose readout from
  the captured final state has cosine >= ``failure_threshold`` to the target)
  is measured (a) against the number of stored pairs at fixed collision
  cosine (capacity sweep) and (b) against the collision cosine at fixed load
  (interference sweep). All five registered variants run; GDN-2 and EDA are
  prior baselines (#37) evaluated on the shared alpha/beta gate path, where
  their tied/zero-erase configurations reduce to KDA exactly (the paper ties
  asserted by #37's tests) — their rows double as regression checks of those
  reductions rather than independent mechanisms.
- **Overwrite / recency** (:class:`OverwriteConfig`). On the #35 overwrite
  task, fresh-target recall accuracy and the stale-dominance rate (fraction
  of queries whose readout is closer to an *overwritten* value than to the
  latest one) are measured against the number of overwrite rounds. EDA runs
  with its erase address fixed to the current key and a pre-registered
  constant erase gate — the paper's ``e_t = k_t`` collapse, the only
  erase-address choice available on the shared task path (this repository has
  no learned address projections); it is a baseline configuration, not a
  tuned design.
- **Edit locality** (:func:`edit_locality_metrics`). From the post-update
  state trajectory ``S_1..S_L`` — replayed from captured traces, never a
  model rerun — each write's *edit* is ``DeltaS_t = S_t - Diag(alpha_t)
  S_{t-1}``. The report tabulates the mean relative edit magnitude
  ``||DeltaS_t||_F / ||S_t||_F`` and the key-axis alignment
  ``||k_t k_t^T DeltaS_t||_F / ||DeltaS_t||_F`` (1.0 when the write vector is
  parallel to the write key, as in KDA/RLS-lite/EDA's ``e = k`` collapse;
  smaller when the edit spreads off-key, as for the precision-gated gain).

Scope notes: synthetic tasks only; sequential reference recurrences; no
wall-clock or production-performance measurements anywhere.
"""

