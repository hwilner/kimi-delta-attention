def _check_common(
    variants: tuple[str, ...],
    seeds: tuple[int, ...],
    batch_size: int,
    key_dim: int,
    value_dim: int,
    failure_threshold: float,
    bootstrap_resamples: int,
    ci_level: float,
) -> None:
    """Shared validation for both experiment configs."""

    unknown = [v for v in variants if v not in available_variants()]
    if unknown:
        raise ValueError(
            f"unknown variants in config: {unknown}; "
            f"registered: {list(available_variants())}"
        )
    if not seeds:
        raise ValueError("seeds must be a non-empty tuple")
    if batch_size <= 0:
        raise ValueError("batch_size must be positive")
    if key_dim < 2 or value_dim <= 0:
        raise ValueError("key_dim must be >= 2 and value_dim positive")
    if not -1.0 <= failure_threshold <= 1.0:
        raise ValueError("failure_threshold must be in [-1, 1]")
    if bootstrap_resamples <= 0:
        raise ValueError("bootstrap_resamples must be positive")
    if not 0.0 < ci_level < 1.0:
        raise ValueError("ci_level must lie in (0, 1)")


@dataclass(frozen=True)
class CapacityConfig:
    """Pre-registered configuration for the capacity/interference sweeps.

    Attributes:
        variants: Registered variant names. GDN-2/EDA run on the shared
            alpha/beta gate path, where they reduce to KDA exactly (baseline
            tie checks, per #37).
        seeds: Task-generator seeds; each seed yields one batch per point.
        batch_size: Sequences per seed.
        key_dim: Key/query dimension (d_h).
        value_dim: Value dimension (d_v).
        gate_seed_offset: Gates are drawn from ``seed + gate_seed_offset`` so
            task content and gates are sampled independently.
        alpha_bias: Bias of the alpha gate distribution
            (``alpha = sigmoid(N(0, 1) + alpha_bias)``), mirroring #28.
        beta_bias: Bias of the beta gate distribution, mirroring #28.
        failure_threshold: Recall cosine at/above which a query counts as
            correctly recalled.
        capacity_loads: ``num_pairs`` values of the capacity sweep
            (sequence length ``L = 2 * num_pairs``), at
            ``capacity_collision_cosine``.
        capacity_collision_cosine: Fixed collision cosine of the capacity
            sweep.
        interference_cosines: Collision cosines of the interference sweep, at
            ``interference_num_pairs``.
        interference_num_pairs: Fixed load of the interference sweep.
        bootstrap_resamples: Cluster-bootstrap resamples over sequences.
        ci_level: Confidence level of the percentile intervals.
        bootstrap_seed: Seed of the bootstrap resampling generator.
    """

    variants: tuple[str, ...] = (
        "kda",
        "kda-rls-lite",
        "precision-gated-kda",
        "gdn-2",
        "eda",
    )
    seeds: tuple[int, ...] = (0, 1, 2)
    batch_size: int = 8
    key_dim: int = 32
    value_dim: int = 32
    gate_seed_offset: int = 10000
    alpha_bias: float = 2.0
    beta_bias: float = 1.0
    failure_threshold: float = 0.5
    capacity_loads: tuple[int, ...] = (2, 4, 8, 16)
    capacity_collision_cosine: float = 0.9
    interference_cosines: tuple[float, ...] = (0.0, 0.5, 0.8, 0.9, 0.99)
    interference_num_pairs: int = 8
    bootstrap_resamples: int = 200
    ci_level: float = 0.95
    bootstrap_seed: int = 0

    def __post_init__(self) -> None:
        _check_common(
            self.variants,
            self.seeds,
            self.batch_size,
            self.key_dim,
            self.value_dim,
            self.failure_threshold,
            self.bootstrap_resamples,
            self.ci_level,
        )
        if not self.capacity_loads or any(n <= 0 for n in self.capacity_loads):
            raise ValueError("capacity_loads must be non-empty positive ints")
        if not -1.0 <= self.capacity_collision_cosine <= 1.0:
            raise ValueError("capacity_collision_cosine must be in [-1, 1]")
        if not self.interference_cosines:
            raise ValueError("interference_cosines must be non-empty")
        if not all(-1.0 <= c <= 1.0 for c in self.interference_cosines):
            raise ValueError("interference_cosines must lie in [-1, 1]")
        if self.interference_num_pairs <= 0:
            raise ValueError("interference_num_pairs must be positive")

    def to_dict(self) -> dict:
        """JSON-serializable snapshot embedded in the experiment report."""

        return {key: list(value) if isinstance(value, tuple) else value
                for key, value in asdict(self).items()}


