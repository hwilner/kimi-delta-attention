# ---------------------------------------------------------------------------
# Shared helpers (gate distribution mirrors the #28/#38 experiments exactly).
# ---------------------------------------------------------------------------


def _sample_gates(
    batch_size: int,
    seq_len: int,
    key_dim: int,
    seed: int,
    alpha_bias: float,
    beta_bias: float,
) -> dict[str, torch.Tensor]:
    """Pre-registered gate distribution: biased sigmoid-normal alpha/beta.

    Identical to the #28 calibration and #38 routing gate distribution, so
    all Phase 4 tables are collected under the same gate regime.
    """

    generator = torch.Generator().manual_seed(seed)
    return {
        "alpha": torch.sigmoid(
            torch.randn(batch_size, seq_len, key_dim, generator=generator)
            + alpha_bias
        ),
        "beta": torch.sigmoid(
            torch.randn(batch_size, seq_len, 1, generator=generator) + beta_bias
        ),
    }


def _write_vectors(trace: dict, keys: torch.Tensor) -> torch.Tensor:
    """Per-step write vector ``w_t`` for state replay (see #27 conventions).

    Same fallback chain as the #28 calibration experiment: the precision-gated
    gain ``g_t`` if present, else the (effective) beta times the key.
    """

    gain = trace.get("gain")
    if isinstance(gain, torch.Tensor):
        return gain  # precision-gated KDA: w_t = g_t
    for name in ("beta_eff", "beta_raw", "beta"):
        beta = trace.get(name)
        if isinstance(beta, torch.Tensor):
            return beta * keys  # KDA / KDA-RLS-lite: w_t = beta_t * k_t
    raise ValueError("trace exposes no write vector (gain / beta_eff / beta_raw / beta)")


def _eda_state_trajectory(
    keys: torch.Tensor,
    values: torch.Tensor,
    alpha: torch.Tensor,
    beta: torch.Tensor,
    erase_address: torch.Tensor,
    erase_gate: torch.Tensor,
    erased_response: torch.Tensor,
) -> torch.Tensor:
    """Replay EDA's post-update states from captured trace tensors.

    Uses the trace entries the EDA variant already exposes (#37), so no model
    rerun is involved:

    - ``S_bar = Diag(alpha_t) S_{t-1}``
    - ``S_e = S_bar - gamma_t e_t r_t^T`` with ``r_t = e_t^T S_bar`` the
      captured ``erased_response``
    - ``S_t = S_e + beta_t k_t (v_t - S_e^T k_t)^T`` (the standard delta
      corrective write at the current key)

    The operations mirror :meth:`EraseThenDeltaVariant.forward` step for step,
    so the final replayed state matches ``DeltaMemoryOutput.final_state`` up
    to floating-point associativity (tested at ``atol=1e-5``, same convention
    as the #27 replay).

    Args:
        keys: ``(batch, L, d_h)`` write keys.
        values: ``(batch, L, d_v)`` write values.
        alpha: ``(batch, L, d_h)`` decay gate.
        beta: ``(batch, L, 1)`` delta gate.
        erase_address: ``(batch, L, d_h)`` applied (L2-normalized) erase
            address from the trace.
        erase_gate: ``(batch, L, 1)`` applied erase gate from the trace.
        erased_response: ``(batch, L, d_v)`` captured ``e_t^T S_bar``.

    Returns:
        Post-update states ``S_1..S_L``, shape ``(batch, L, d_h, d_v)``.
    """

    batch, seq_len, head_dim = keys.shape
    value_dim = values.shape[-1]
    for name, tensor in (
        ("alpha", alpha),
        ("erase_address", erase_address),
    ):
        if tensor.shape != (batch, seq_len, head_dim):
            raise ValueError(
                f"{name} must have shape {(batch, seq_len, head_dim)}, "
                f"got {tuple(tensor.shape)}"
            )
    for name, tensor in (("beta", beta), ("erase_gate", erase_gate)):
        if tensor.shape != (batch, seq_len, 1):
            raise ValueError(
                f"{name} must have shape {(batch, seq_len, 1)}, "
                f"got {tuple(tensor.shape)}"
            )
    if erased_response.shape != (batch, seq_len, value_dim):
        raise ValueError(
            f"erased_response must have shape {(batch, seq_len, value_dim)}, "
            f"got {tuple(erased_response.shape)}"
        )

    state = keys.new_zeros(batch, head_dim, value_dim)
    states = []
    for t in range(seq_len):
        s_bar = alpha[:, t].unsqueeze(-1) * state
        # Erase at the independent address using the captured response.
        s_erased = s_bar - erase_gate[:, t].unsqueeze(-1) * torch.bmm(
            erase_address[:, t].unsqueeze(-1), erased_response[:, t].unsqueeze(1)
        )
        # Delta corrective write at the current key (identical to KDACore).
        k_response = torch.bmm(
            s_erased.transpose(1, 2), keys[:, t].unsqueeze(-1)
        ).squeeze(-1)
        state = s_erased + torch.bmm(
            (beta[:, t] * keys[:, t]).unsqueeze(-1),
            (values[:, t] - k_response).unsqueeze(1),
        )
        states.append(state.clone())
    return torch.stack(states, dim=1)


def edit_locality_metrics(
    states: torch.Tensor,
    keys: torch.Tensor,
    alpha: torch.Tensor,
    *,
    eps: float = _EPS,
) -> dict:
    """Edit magnitude and key-axis alignment of each write in a trajectory.

    The *edit* of step ``t`` is ``DeltaS_t = S_t - Diag(alpha_t) S_{t-1}``
    (the state change excluding decay). Two scalar metrics, each averaged
    over batch and steps:

    - ``relative_update_norm``: ``||DeltaS_t||_F / (||S_t||_F + eps)`` — how
      large each edit is relative to the state it lands in. At ``t = 0`` the
      state is empty, so the first edit always scores 1.
    - ``key_axis_alignment``: ``||k_t k_t^T DeltaS_t||_F /
      (||DeltaS_t||_F + eps)`` — the fraction of the edit concentrated along
      the write key's row axis. Exactly 1 when the write vector is parallel
      to the key (KDA ``beta k``, RLS-lite ``beta_eff k``, EDA's
      ``e_t = k_t`` collapse); smaller when the edit spreads off-key (the
      precision-gated gain ``g_t``). Assumes unit-norm keys, which all #35
      task generators produce.
    """

    if states.dim() != 4:
        raise ValueError(f"states must have shape (batch, L, d_h, d_v), got {states.shape}")
    batch, seq_len, head_dim, _ = states.shape
    if keys.shape != (batch, seq_len, head_dim):
        raise ValueError(
            f"keys must have shape {(batch, seq_len, head_dim)}, got {tuple(keys.shape)}"
        )
    if alpha.shape != (batch, seq_len, head_dim):
        raise ValueError(
            f"alpha must have shape {(batch, seq_len, head_dim)}, got {tuple(alpha.shape)}"
        )
    if eps <= 0:
        raise ValueError(f"eps must be positive, got {eps}")

    initial = torch.zeros_like(states[:, :1])
    previous = torch.cat([initial, states[:, :-1]], dim=1)
    delta = states - alpha.unsqueeze(-1) * previous  # (B, L, d_h, d_v)

    delta_norm = delta.flatten(2).norm(dim=-1)  # (B, L), Frobenius
    state_norm = states.flatten(2).norm(dim=-1)
    # Key-axis projection: k_t (k_t^T DeltaS_t); keys are unit norm.
    projected = torch.einsum("blh,blhv->blv", keys, delta)
    projected = torch.einsum("blh,blv->blhv", keys, projected)
    projected_norm = projected.flatten(2).norm(dim=-1)

    relative = delta_norm / (state_norm + eps)
    alignment = projected_norm / (delta_norm + eps)
    return {
        "relative_update_norm": float(relative.mean()),
        "key_axis_alignment": float(alignment.mean()),
        "num_steps": int(batch * seq_len),
    }


def _rate_with_ci(
    labels: np.ndarray,
    groups: np.ndarray,
    *,
    resamples: int,
    level: float,
    seed: int,
) -> dict:
    """Mean of a per-item 0/1 rate plus its cluster-bootstrap CI (#28 style)."""

    labels = np.asarray(labels, dtype=np.float64)
    return {
        "value": float(labels.mean()),
        "ci": list(
            bootstrap_ci(
                (labels,),
                groups,
                lambda lab: float(lab.mean()),
                resamples=resamples,
                level=level,
                seed=seed,
            )
        ),
    }


