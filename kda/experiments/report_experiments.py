def _collect_capacity_point(
    variant_name: str,
    num_pairs: int,
    collision_cosine: float,
    config: CapacityConfig,
) -> dict:
    """Recall outcomes for one (load or cosine) operating point.

    One write pass per seed on the key-collision task; every key is then
    recalled against the captured final state (the variant's own readout
    ``S_L^T k_i`` on stored tensors — not a rerun), exactly as in #28.
    """

    success_parts, group_parts, cosine_parts = [], [], []
    for seed_index, seed in enumerate(config.seeds):
        task = generate_key_collision_batch(
            KeyCollisionTaskConfig(
                batch_size=config.batch_size,
                num_pairs=num_pairs,
                key_dim=config.key_dim,
                value_dim=config.value_dim,
                collision_cosine=collision_cosine,
                seed=seed,
                shuffle_queries=False,  # queries = keys: write-step alignment
            )
        )
        gates = _sample_gates(
            config.batch_size,
            task.keys.shape[1],
            config.key_dim,
            seed + config.gate_seed_offset,
            config.alpha_bias,
            config.beta_bias,
        )
        variant = create_variant(
            variant_name, head_dim=config.key_dim, value_dim=config.value_dim
        )
        with torch.no_grad():
            result = variant(task.keys, task.keys, task.values, gates=gates)
            recall = torch.einsum("bhv,blh->blv", result.final_state, task.keys)
            cosine = F.cosine_similarity(recall, task.values, dim=-1, eps=_EPS)
        success_parts.append(
            (cosine >= config.failure_threshold).to(torch.float64).numpy()
        )
        batch, seq_len = task.keys.shape[:2]
        group_parts.append(
            (np.arange(batch) + seed_index * batch).repeat(seq_len)
        )
        cosine_parts.append(cosine.numpy())

    success = np.concatenate([p.reshape(-1) for p in success_parts])
    groups = np.concatenate(group_parts)
    cosines = np.concatenate([p.reshape(-1) for p in cosine_parts])
    return {
        "num_items": int(success.size),
        "recall_accuracy": _rate_with_ci(
            success,
            groups,
            resamples=config.bootstrap_resamples,
            level=config.ci_level,
            seed=config.bootstrap_seed,
        ),
        "mean_recall_cosine": float(cosines.mean()),
    }


def run_capacity_experiment(config: CapacityConfig) -> dict:
    """Run the pre-registered capacity/interference sweeps.

    For each variant the experiment measures recall accuracy (a) over
    ``config.capacity_loads`` at the fixed capacity collision cosine and
    (b) over ``config.interference_cosines`` at the fixed interference load.
    All points carry cluster-bootstrap CIs over sequences; GDN-2/EDA run in
    their tied/zero-erase configurations, where they reduce to KDA exactly
    (baseline regression checks, per #37).

    Returns:
        A JSON-serializable dict embedding the full config snapshot.
    """

    report = {
        "experiment": "phase4-capacity-interference",
        "issue": 34,
        "description": (
            "Recall accuracy vs stored-pair count (capacity) and vs key "
            "collision cosine (interference) on the #35 key-collision task. "
            "Pre-registered in the embedded config; CIs are cluster bootstrap "
            "over sequences; GDN-2/EDA run on the shared alpha/beta gate "
            "path where they coincide with KDA (paper ties, #37)."
        ),
        "config": config.to_dict(),
        "capacity_sweep": {},
        "interference_sweep": {},
    }
    for variant_name in config.variants:
        report["capacity_sweep"][variant_name] = {
            "collision_cosine": config.capacity_collision_cosine,
            "points": [
                dict(
                    num_pairs=num_pairs,
                    **_collect_capacity_point(
                        variant_name,
                        num_pairs,
                        config.capacity_collision_cosine,
                        config,
                    ),
                )
                for num_pairs in config.capacity_loads
            ],
        }
        report["interference_sweep"][variant_name] = {
            "num_pairs": config.interference_num_pairs,
            "points": [
                dict(
                    collision_cosine=cosine,
                    **_collect_capacity_point(
                        variant_name,
                        config.interference_num_pairs,
                        cosine,
                        config,
                    ),
                )
                for cosine in config.interference_cosines
            ],
        }
    return report


