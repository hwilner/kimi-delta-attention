def _collect_overwrite_point(
    variant_name: str,
    num_updates: int,
    config: OverwriteConfig,
) -> dict:
    """Fresh/stale recall outcomes and edit locality for one overwrite count.

    One write pass per seed on the overwrite task (EDA additionally receives
    the pre-registered ``erase_address = current key`` + constant erase
    gate). Fresh recall uses the captured final state; stale dominance
    compares each readout's cosine to the freshest target against its best
    cosine to any overwritten (stale) target. Edit locality is computed from
    the replayed/derived state trajectory — never a model rerun.
    """

    fresh_parts, stale_parts, group_parts, cosine_parts = [], [], [], []
    locality_parts = []
    for seed_index, seed in enumerate(config.seeds):
        task = generate_overwrite_batch(
            OverwriteTaskConfig(
                batch_size=config.batch_size,
                num_keys=config.num_keys,
                num_updates=num_updates,
                key_dim=config.key_dim,
                value_dim=config.value_dim,
                seed=seed,
            )
        )
        batch, seq_len = task.sequence_keys.shape[:2]
        gates = _sample_gates(
            batch,
            seq_len,
            config.key_dim,
            seed + config.gate_seed_offset,
            config.alpha_bias,
            config.beta_bias,
        )
        if variant_name == "eda":
            # Pre-registered baseline arm: erase at the current key with a
            # constant gate (the paper's e_t = k_t collapse; not tuned).
            gates = dict(gates)
            gates["erase_address"] = task.sequence_keys
            gates["erase_gate"] = torch.full(
                (batch, seq_len, 1), config.eda_erase_gate
            )
        variant = create_variant(
            variant_name, head_dim=config.key_dim, value_dim=config.value_dim
        )
        with torch.no_grad():
            result = variant(
                task.sequence_keys,
                task.sequence_keys,
                task.sequence_values,
                gates=gates,
                return_trace=True,
            )
            recall = torch.einsum(
                "bhv,bkh->bkv", result.final_state, task.queries
            )
            fresh_cosine = F.cosine_similarity(
                recall, task.final_targets, dim=-1, eps=_EPS
            )  # (B, K)
            stale_cosine = F.cosine_similarity(
                recall.unsqueeze(2), task.stale_targets, dim=-1, eps=_EPS
            ).max(dim=2).values  # (B, K)

            if variant_name == "eda":
                states = _eda_state_trajectory(
                    task.sequence_keys,
                    task.sequence_values,
                    gates["alpha"],
                    gates["beta"],
                    result.trace["erase_address"],
                    result.trace["erase_gate"],
                    result.trace["erased_response"],
                )
            else:
                states = replay_state_trajectory(
                    task.sequence_keys,
                    task.sequence_values,
                    gates["alpha"],
                    _write_vectors(result.trace, task.sequence_keys),
                )
            locality_parts.append(
                edit_locality_metrics(states, task.sequence_keys, gates["alpha"])
            )

        fresh_parts.append(
            (fresh_cosine >= config.failure_threshold).to(torch.float64).numpy()
        )
        stale_parts.append(
            (stale_cosine > fresh_cosine).to(torch.float64).numpy()
        )
        group_parts.append(np.arange(batch) + seed_index * batch)
        cosine_parts.append(fresh_cosine.numpy())

    fresh = np.concatenate([p.reshape(-1) for p in fresh_parts])
    stale = np.concatenate([p.reshape(-1) for p in stale_parts])
    groups = np.concatenate(
        [g.repeat(config.num_keys) for g in group_parts]
    )
    fresh_cosines = np.concatenate([p.reshape(-1) for p in cosine_parts])
    return {
        "num_items": int(fresh.size),
        "fresh_recall_accuracy": _rate_with_ci(
            fresh,
            groups,
            resamples=config.bootstrap_resamples,
            level=config.ci_level,
            seed=config.bootstrap_seed,
        ),
        "mean_fresh_cosine": float(fresh_cosines.mean()),
        "stale_dominance_rate": _rate_with_ci(
            stale,
            groups,
            resamples=config.bootstrap_resamples,
            level=config.ci_level,
            seed=config.bootstrap_seed,
        ),
        "edit_relative_update_norm": float(
            np.mean([p["relative_update_norm"] for p in locality_parts])
        ),
        "edit_key_axis_alignment": float(
            np.mean([p["key_axis_alignment"] for p in locality_parts])
        ),
    }


def run_overwrite_experiment(config: OverwriteConfig) -> dict:
    """Run the pre-registered overwrite/recency experiment.

    For each variant the experiment measures fresh-target recall accuracy,
    the stale-dominance rate, and the edit-locality metrics over
    ``config.update_counts`` overwrite rounds. EDA runs in its pre-registered
    ``e_t = k_t`` collapse with the constant erase gate from the config.
    Rates carry cluster-bootstrap CIs over sequences; flat/negative results
    are reported as-is.

    Returns:
        A JSON-serializable dict embedding the full config snapshot.
    """

    report = {
        "experiment": "phase4-overwrite-recency",
        "issue": 34,
        "description": (
            "Fresh-target recall, stale-value dominance, and edit locality "
            "vs overwrite rounds on the #35 overwrite task. Pre-registered "
            "in the embedded config; CIs are cluster bootstrap over "
            "sequences; the EDA arm erases at the current key with the "
            "config's constant gate (e_t = k_t collapse, a baseline "
            "configuration, not a tuned design)."
        ),
        "config": config.to_dict(),
        "variants": {},
    }
    for variant_name in config.variants:
        report["variants"][variant_name] = {
            "num_keys": config.num_keys,
            "points": [
                dict(
                    num_updates=num_updates,
                    **_collect_overwrite_point(variant_name, num_updates, config),
                )
                for num_updates in config.update_counts
            ],
        }
    return report
